#!/usr/bin/env node
// Draws the Bluesky profile avatar as an SVG master: the front of a blue
// TARC-style low-floor bus whose amber LED destination sign reads "502", the
// Louisville area code. It carries no TARC logo or wordmark, and it draws the
// sign as LED dots rather than <text> so it renders the same on every host.
//
// Usage (from the monorepo root):
//   node apps/insights/scripts/tarc/draw-bus-avatar.js [--alert-badge] [--out=path.svg]
//   node apps/insights/scripts/tarc/render-bus-avatar.js   # SVG -> PNG for upload
//
// Default output is branding/bluesky-bus-avatar.svg, which render-bus-avatar.js
// rasterizes and set-profile.js uploads. --alert-badge adds a red "!" badge to
// the top-right corner of the bus. The livery colors approximate TARC's current
// blue fleet; retune them in PALETTE.

const fs = require('node:fs');
const path = require('node:path');

const DEFAULT_OUT = path.resolve(__dirname, '../../../../branding/bluesky-bus-avatar.svg');

const PALETTE = {
  blue: '#0057B8', // main body
  blueDark: '#003C82', // lower-body shading
  blueLight: '#3FA9F5', // accent swoosh
  white: '#FFFFFF',
  ledOn: '#FFB81C',
  ledOff: '#3A2A12',
  glassTop: '#14243A',
  glassBottom: '#2E4B6B',
  bgInner: '#FFD54A',
  bgOuter: '#FF9F1C',
  badge: '#E4002B',
};

// 5x7 dot-matrix glyphs for the destination sign.
const FONT = {
  0: ['01110', '10001', '10001', '10001', '10001', '10001', '01110'],
  2: ['01110', '10001', '00001', '00010', '00100', '01000', '11111'],
  5: ['11111', '10000', '11110', '00001', '00001', '10001', '01110'],
};

const SIGN_TEXT = '502';
const SIGN = { cx: 500, y: 208, w: 420, h: 196 };
const DOT = { pitch: 21, lit: 8.2, unlit: 6 };

// Lit and unlit dot centres, one blank column between characters.
function signDots(text) {
  const rows = 7;
  const cols = text.length * 6 - 1;
  const x0 = SIGN.cx - ((cols - 1) * DOT.pitch) / 2;
  const y0 = SIGN.y + SIGN.h / 2 - ((rows - 1) * DOT.pitch) / 2;
  const lit = [];
  const unlit = [];
  for (let col = 0; col < cols; col += 1) {
    const glyph = FONT[text[Math.floor(col / 6)]];
    const glyphCol = col % 6;
    for (let row = 0; row < rows; row += 1) {
      const point = [x0 + col * DOT.pitch, y0 + row * DOT.pitch];
      if (glyphCol < 5 && glyph[row][glyphCol] === '1') lit.push(point);
      else unlit.push(point);
    }
  }
  return { lit, unlit };
}

function circles(points, r, fill) {
  return points
    .map(([x, y]) => `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r}" fill="${fill}"/>`)
    .join('\n    ');
}

const BUS_OUTLINE =
  'M300 172 H700 Q776 172 778 250 L784 760 Q784 808 740 808 H260 Q216 808 216 760 L222 250 Q224 172 300 172 Z';
const WINDSHIELD =
  'M262 432 H738 Q752 432 752 448 V610 Q752 646 716 650 L540 662 H460 L284 650 Q248 646 248 610 V448 Q248 432 262 432 Z';

function buildBusAvatarSvg({ alertBadge = false } = {}) {
  const c = PALETTE;
  const { lit, unlit } = signDots(SIGN_TEXT);
  const sx = SIGN.cx - SIGN.w / 2;
  const sy = SIGN.y;

  const badge = alertBadge
    ? `
  <!-- alert badge -->
  <g transform="translate(760 205)">
    <circle r="74" fill="${c.badge}" stroke="${c.white}" stroke-width="16"/>
    <rect x="-11" y="-44" width="22" height="56" rx="11" fill="${c.white}"/>
    <circle cx="0" cy="34" r="12" fill="${c.white}"/>
  </g>`
    : '';

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" width="1024" height="1024" role="img" aria-labelledby="title description">
  <title id="title">Louisville Transit Alerts bus avatar</title>
  <desc id="description">The front of a blue city bus on an amber background, with an amber LED destination sign reading 502.${alertBadge ? ' A red alert badge sits on its top-right corner.' : ''}</desc>
  <!-- Generated by apps/insights/scripts/tarc/draw-bus-avatar.js; edit the script, not this file. -->
  <defs>
    <radialGradient id="bg" cx="50%" cy="40%" r="75%">
      <stop offset="0" stop-color="${c.bgInner}"/>
      <stop offset="1" stop-color="${c.bgOuter}"/>
    </radialGradient>
    <linearGradient id="body" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${c.blue}"/>
      <stop offset="0.75" stop-color="${c.blue}"/>
      <stop offset="1" stop-color="${c.blueDark}"/>
    </linearGradient>
    <linearGradient id="bodyside" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#000" stop-opacity="0.22"/>
      <stop offset="0.12" stop-color="#000" stop-opacity="0"/>
      <stop offset="0.88" stop-color="#000" stop-opacity="0"/>
      <stop offset="1" stop-color="#000" stop-opacity="0.22"/>
    </linearGradient>
    <linearGradient id="glass" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${c.glassTop}"/>
      <stop offset="1" stop-color="${c.glassBottom}"/>
    </linearGradient>
    <linearGradient id="shine" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0.28"/>
      <stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </linearGradient>
    <radialGradient id="led" cx="40%" cy="35%" r="70%">
      <stop offset="0" stop-color="#FFF1C2"/>
      <stop offset="0.45" stop-color="${c.ledOn}"/>
      <stop offset="1" stop-color="#E08A00"/>
    </radialGradient>
    <radialGradient id="lamp" cx="50%" cy="50%" r="50%">
      <stop offset="0" stop-color="#FFFFFF"/>
      <stop offset="0.6" stop-color="#FFF6D6"/>
      <stop offset="1" stop-color="#E6D9A8"/>
    </radialGradient>
    <filter id="glow" x="-20%" y="-40%" width="140%" height="180%">
      <feGaussianBlur stdDeviation="7"/>
    </filter>
    <filter id="soft" x="-30%" y="-30%" width="160%" height="160%">
      <feGaussianBlur stdDeviation="14"/>
    </filter>
    <clipPath id="glassclip">
      <path d="${WINDSHIELD}"/>
    </clipPath>
  </defs>

  <!-- Background; Bluesky crops the avatar to a circle, and the bus stays inside it. -->
  <rect width="1000" height="1000" fill="url(#bg)"/>
  <g opacity="0.16" fill="#fff">
    <path d="M500 520 L120 0 H330 Z"/>
    <path d="M500 520 L670 0 H880 Z"/>
    <path d="M500 520 L1000 260 V470 Z"/>
    <path d="M500 520 L0 260 V470 Z"/>
  </g>
  <ellipse cx="500" cy="872" rx="330" ry="34" fill="#000" opacity="0.28" filter="url(#soft)"/>

  <!-- Tires -->
  <rect x="236" y="792" width="78" height="82" rx="16" fill="#151515"/>
  <rect x="686" y="792" width="78" height="82" rx="16" fill="#151515"/>

  <!-- Mirror arms and mirrors -->
  <g fill="none" stroke="#1A1A1A" stroke-width="13" stroke-linecap="round" stroke-linejoin="round">
    <path d="M262 250 Q196 252 186 318 L186 372"/>
    <path d="M738 250 Q804 252 814 318 L814 372"/>
  </g>
  <rect x="152" y="360" width="62" height="118" rx="22" fill="#1A1A1A"/>
  <rect x="786" y="360" width="62" height="118" rx="22" fill="#1A1A1A"/>
  <rect x="162" y="372" width="18" height="70" rx="9" fill="#fff" opacity="0.18"/>
  <rect x="796" y="372" width="18" height="70" rx="9" fill="#fff" opacity="0.18"/>

  <!-- Body -->
  <path d="${BUS_OUTLINE}" fill="url(#body)"/>
  <path d="${BUS_OUTLINE}" fill="url(#bodyside)"/>
  <path d="M300 186 H700 Q752 186 762 232" fill="none" stroke="#fff" stroke-opacity="0.35" stroke-width="8" stroke-linecap="round"/>

  <!-- Accent swoosh across the lower front -->
  <path d="M216 742 C340 700 520 724 640 690 C700 672 748 650 784 628 L784 676 C744 700 700 716 640 730 C520 760 350 744 216 790 Z" fill="${c.blueLight}"/>
  <path d="M216 712 C340 668 520 694 640 660 C700 642 748 620 784 598 L784 616 C748 638 700 660 640 676 C520 708 340 686 216 732 Z" fill="${c.white}"/>

  <!-- Destination sign: "${SIGN_TEXT}" in amber LEDs -->
  <rect x="${sx - 12}" y="${sy - 12}" width="${SIGN.w + 24}" height="${SIGN.h + 24}" rx="26" fill="#0B0B0B"/>
  <rect x="${sx}" y="${sy}" width="${SIGN.w}" height="${SIGN.h}" rx="16" fill="#141109"/>
  <g>
    ${circles(unlit, DOT.unlit, c.ledOff)}
  </g>
  <g filter="url(#glow)" opacity="0.85">
    ${circles(lit, DOT.lit + 2, c.ledOn)}
  </g>
  <g>
    ${circles(lit, DOT.lit, 'url(#led)')}
  </g>
  <path d="M${sx + 10} ${sy + 10} H${sx + SIGN.w - 10} L${sx + SIGN.w - 120} ${sy + 70} H${sx + 10} Z" fill="#fff" opacity="0.06"/>

  <!-- Windshield -->
  <path d="${WINDSHIELD}" fill="url(#glass)" stroke="#0B0B0B" stroke-width="10" stroke-linejoin="round"/>
  <g clip-path="url(#glassclip)">
    <path d="M250 432 H420 L300 662 H250 Z" fill="url(#shine)"/>
    <path d="M460 432 H520 L400 662 H340 Z" fill="#fff" opacity="0.08"/>
    <rect x="495" y="432" width="10" height="232" fill="#0B0B0B"/>
    <path d="M318 640 L430 520" stroke="#0B0B0B" stroke-width="7" stroke-linecap="round"/>
    <path d="M568 646 L680 526" stroke="#0B0B0B" stroke-width="7" stroke-linecap="round"/>
  </g>

  <!-- Headlight clusters -->
  <rect x="238" y="676" width="118" height="58" rx="18" fill="#0E0E0E"/>
  <circle cx="272" cy="705" r="20" fill="url(#lamp)"/>
  <circle cx="318" cy="705" r="16" fill="url(#lamp)"/>
  <rect x="340" y="694" width="10" height="22" rx="4" fill="#FF9F1C"/>
  <rect x="644" y="676" width="118" height="58" rx="18" fill="#0E0E0E"/>
  <circle cx="728" cy="705" r="20" fill="url(#lamp)"/>
  <circle cx="682" cy="705" r="16" fill="url(#lamp)"/>
  <rect x="650" y="694" width="10" height="22" rx="4" fill="#FF9F1C"/>

  <!-- Folded bike rack -->
  <g fill="none" stroke="#1C1C1C" stroke-width="12" stroke-linejoin="round" stroke-linecap="round">
    <path d="M386 772 V694 Q386 680 400 680 H600 Q614 680 614 694 V772"/>
    <path d="M386 728 H614"/>
  </g>

  <!-- Bumper -->
  <rect x="226" y="764" width="548" height="48" rx="20" fill="#121212"/>
  <rect x="246" y="772" width="508" height="8" rx="4" fill="#fff" opacity="0.10"/>${badge}
</svg>
`;
}

function main() {
  const argv = require('minimist')(process.argv.slice(2), {
    boolean: ['alert-badge'],
    string: ['out'],
  });
  const out = argv.out ? path.resolve(argv.out) : DEFAULT_OUT;
  fs.writeFileSync(out, buildBusAvatarSvg({ alertBadge: argv['alert-badge'] }));
  console.log(`Wrote ${out}`);
}

if (require.main === module) main();

module.exports = { buildBusAvatarSvg, DEFAULT_OUT };
